#!/usr/bin/env node
/**
 * build-orla-kb.mjs
 *
 * Builds Orla's knowledge base from the site's own published pages (site/content/**.md,
 * which build-content.mjs generates from the repo's canonical docs). Every chunk keeps the
 * URL of the page it came from, so Orla can point readers to the source.
 *
 * Output: site/api/_orla-kb.js (CommonJS; the leading underscore keeps it from being
 * deployed as its own route). Committed, and regenerated on every build (prebuild).
 *
 * Only PUBLISHED framework pages go in. Nothing private, nothing about pricing.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(__dirname, "..");
const CONTENT = path.join(SITE, "content");
const OUT = path.join(SITE, "api", "_orla-kb.js");
const PRIMER = path.join(__dirname, "orla-primer.md");
const MAX = 2400; // characters per chunk

// Unlisted / navigational pages that add noise rather than knowledge.
const SKIP = [/^blog\/index\.md$/,/^explore\/open-source-launch/, /_includes\//, /architecture 2\//];

async function walk(dir) {
  const out = [];
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (e.name.endsWith(".md")) out.push(p);
  }
  return out;
}

function clean(md) {
  return md
    .replace(/^---[\s\S]*?\n---\n/, "")          // front matter
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")          // images
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")       // links -> text
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function urlFor(rel) {
  const r = rel.replace(/\\/g, "/").replace(/\.md$/, "");
  if (r === "index") return "/";
  return "/" + r.replace(/\/index$/, "");
}

function chunk(text, pageTitle) {
  const parts = text.split(/\n(?=## )/);
  const chunks = [];
  for (const part of parts) {
    const h = (part.match(/^##\s+(.+)/) || [])[1];
    const heading = h ? `${pageTitle} — ${h.trim()}` : pageTitle;
    if (part.length <= MAX) { chunks.push({ heading, text: part.trim() }); continue; }
    let cur = "";
    for (const para of part.split(/\n\n/)) {
      if (cur && cur.length + para.length > MAX) { chunks.push({ heading, text: cur.trim() }); cur = ""; }
      cur += (cur ? "\n\n" : "") + para;
    }
    if (cur.trim()) chunks.push({ heading, text: cur.trim() });
  }
  // Merge neighbouring small sections so each chunk carries enough context to answer from.
  const merged = [];
  for (const c of chunks) {
    const last = merged[merged.length - 1];
    if (last && last.text.length + c.text.length < MAX * 0.75) {
      last.text += "\n\n" + c.text;
      if (last.heading === pageTitle) last.heading = c.heading;
    } else merged.push({ ...c });
  }
  return merged.filter((c) => c.text.replace(/[#\s]/g, "").length > 80);
}

const files = await walk(CONTENT);
const chunks = [];
for (const abs of files) {
  const rel = path.relative(CONTENT, abs).replace(/\\/g, "/");
  if (SKIP.some((rx) => rx.test(rel))) continue;
  const md = clean(await fs.readFile(abs, "utf8"));
  if (!md) continue;
  const title = ((md.match(/^#\s+(.+)/m) || [])[1] || rel).trim();
  for (const c of chunk(md, title)) chunks.push({ url: urlFor(rel), heading: c.heading, text: c.text });
}

const primer = await fs.readFile(PRIMER, "utf8");
const body = `// GENERATED by scripts/build-orla-kb.mjs — do not edit by hand.\n` +
  `module.exports = ${JSON.stringify({ builtAt: new Date().toISOString(), primer, chunks })};\n`;
await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(OUT, body);
console.log(`orla-kb: ${chunks.length} chunks from ${files.length} pages (${Math.round(body.length / 1024)} KB)`);
